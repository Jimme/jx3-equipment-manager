import { expect, test } from '@playwright/test';

test('共享库存、候选穿戴、附魔归属、掉落转入清空及账号隔离', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', e => errors.push(e.message));
  const cycle = await (await request.post('/api/cycles', { data: { name: '日常流程测试周期' } })).json();
  const account = await (await request.post('/api/accounts', { data: { name: '日常流程测试账号' } })).json();
  const first = await (await request.post(`/api/accounts/${account.id}/characters`, { data: { name: '日常角色甲' } })).json();
  const second = await (await request.post(`/api/accounts/${account.id}/characters`, { data: { name: '日常角色乙' } })).json();
  await request.post(`/api/cycles/${cycle.id}/sources`, { data: { source_type: '测试', name: '流程测试来源', short_label: '测', default_grade: 1110 } });
  await request.put(`/api/accounts/${account.id}/preferences`, { data: { target_grade: 1110, comparison_mode: 'combined' } });
  const state = async () => (await request.get(`/api/accounts/${account.id}/daily`)).json();

  await page.goto('/');
  await page.getByLabel('游戏账号', { exact: true }).selectOption({ label: account.name });
  await expect(page.getByRole('button', { name: '日常角色甲 帽子', exact: true })).toBeVisible();
  await page.getByRole('tab', { name: '共享仓库', exact: true }).click();
  await page.getByRole('button', { name: '添加库存', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('来源预设').selectOption({ label: '流程测试来源' });
  await dialog.getByLabel('是否有体质孔').selectOption('true');
  await dialog.getByLabel('绿字是否达标').selectOption('true');
  await dialog.getByLabel('录入数量').fill('2');
  await dialog.getByRole('button', { name: '保存库存', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(2);
  await page.getByRole('tabpanel').getByRole('button', { name: '给角色穿戴', exact: true }).click();
  await dialog.getByLabel('穿戴角色').selectOption(first.id);
  await dialog.getByText('附魔', { exact: true }).click();
  await dialog.getByLabel('附魔', { exact: true }).selectOption('none');
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(1);
  expect((await state()).warehouse[0].choices.enchant.state).toBe('unknown');
  let matrix = await (await request.get(`/api/accounts/${account.id}/matrix`)).json();
  expect(matrix.cells[first.id].hat.choices.enchant.state).toBe('none');
  await page.getByRole('tab', { name: '缺口明细', exact: true }).click();
  await page.getByLabel('只看仓库可改善').check();
  await page.getByLabel('缺口角色').selectOption(second.id);
  await expect(page.getByRole('tabpanel').locator('tbody tr')).toHaveCount(1);
  await page.getByRole('tabpanel').getByRole('button', { name: '测+ · 1110 品 · 可用 1 件', exact: true }).click();
  await expect(dialog.locator('.fixed-field').filter({ hasText: '角色' })).toContainText('日常角色乙');
  await expect(dialog.getByLabel('穿戴部位')).toHaveCount(0);
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse).toHaveLength(0);
  await expect(page.getByRole('tabpanel').getByText('当前没有可改善项，可取消筛选查看全部缺口。')).toBeVisible();

  await page.getByRole('tab', { name: '本次团本掉落', exact: true }).click();
  await page.getByRole('button', { name: '记录掉落', exact: true }).click();
  await dialog.getByLabel('库存装备部位').selectOption('weapon');
  await dialog.getByLabel('来源预设').selectOption({ label: '流程测试来源' });
  await dialog.getByLabel('是否有体质孔').selectOption('true');
  await dialog.getByLabel('绿字是否达标').selectOption('true');
  await dialog.getByLabel('录入数量').fill('3');
  await dialog.getByText('更多信息', { exact: true }).click();
  await dialog.getByLabel('五彩石', { exact: true }).selectOption('configured');
  await dialog.getByLabel('五彩石名称', { exact: true }).fill('仅记录名称的测试五彩石');
  await dialog.getByRole('button', { name: '保存掉落', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse).toHaveLength(0);
  expect((await state()).drops[0].quantity).toBe(3);
  await page.getByRole('button', { name: '转入仓库', exact: true }).click();
  await dialog.getByLabel('实际获得的数量').fill('2');
  await dialog.getByRole('button', { name: '确认转入', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(2);
  expect((await state()).drops[0].quantity).toBe(1);
  page.once('dialog', prompt => prompt.accept());
  await page.getByRole('button', { name: '清空本次掉落', exact: true }).click();
  await expect(page.getByText('本次还没有记录掉落。')).toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(2);
  await page.getByRole('tab', { name: '共享仓库', exact: true }).click();
  await page.getByRole('button', { name: '给角色穿戴', exact: true }).click();
  await dialog.getByLabel('穿戴角色').selectOption(first.id);
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  matrix = await (await request.get(`/api/accounts/${account.id}/matrix`)).json();
  expect(matrix.cells[first.id].weapon.choices.rainbow.name).toBe('仅记录名称的测试五彩石');
  expect(matrix.cells[first.id].weapon.choices.rainbow.constitution).toBeNull();
  expect(matrix.constitution.stacks).toBeNull();
  await page.getByRole('button', { name: '日常角色甲 武器', exact: true }).click();
  await dialog.getByText('更多信息', { exact: true }).click();
  await expect(dialog.getByLabel('五彩石', { exact: true })).toHaveValue('configured');
  await dialog.getByLabel('真实品级', { exact: true }).fill('1200');
  await expect(dialog.getByLabel('五彩石', { exact: true })).toHaveValue('configured');
  await dialog.getByRole('button', { name: /^保存(装备|记录)$/ }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].choices.rainbow.name).toBe('仅记录名称的测试五彩石');

  await page.getByRole('button', { name: /^修改.*数量$/ }).click();
  const item = (await state()).warehouse[0];
  await request.post(`/api/accounts/${account.id}/warehouse/${item.id}/quantity`, { data: { request_id: crypto.randomUUID(), quantity: 2, expected_version: item.version } });
  await page.getByLabel('实际数量').fill('3');
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('记录已变化');
  await page.getByRole('button', { name: '取消修改数量', exact: true }).click();
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('已刷新');
  await page.getByRole('button', { name: '操作记录', exact: true }).click();
  await expect(page.getByRole('tabpanel').getByText('掉落转入仓库', { exact: true })).toBeVisible();
  await expect(page.getByRole('tabpanel').getByText('清空掉落', { exact: true })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1080 });
  await page.locator('.daily-section').screenshot({ path: '../.tools/screenshots/phase2-history.png' });
  await page.getByRole('tab', { name: '共享仓库', exact: true }).click();
  await page.locator('.daily-section').screenshot({ path: '../.tools/screenshots/phase2-warehouse.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.locator('.daily-section').screenshot({ path: '../.tools/screenshots/phase2-mobile.png' });

  const other = await (await request.post('/api/accounts', { data: { name: '日常隔离测试账号' } })).json();
  await page.reload();
  await page.getByLabel('游戏账号', { exact: true }).selectOption(other.id);
  await expect(page.getByText('共享仓库还没有库存。')).toBeVisible();
  await page.getByRole('tab', { name: '本次团本掉落', exact: true }).click();
  await expect(page.getByText('本次还没有记录掉落。')).toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(2);
  expect(errors).toEqual([]);
});
