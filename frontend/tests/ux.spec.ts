import { expect, test } from '@playwright/test';

test('精简流程：格子选库存、纠错保留附魔、显式换装、单件转入与行内数量重试', async ({ page, request }) => {
  const failures: string[] = [];
  page.on('pageerror', e => failures.push(e.message));
  const cycle = await (await request.post('/api/cycles', { data: { name: '交互验收测试周期' } })).json();
  const account = await (await request.post('/api/accounts', { data: { name: '交互验收测试账号' } })).json();
  const prefix = `/api/accounts/${account.id}`;
  const a = await (await request.post(`${prefix}/characters`, { data: { name: '交互甲' } })).json();
  const b = await (await request.post(`${prefix}/characters`, { data: { name: '交互乙' } })).json();
  const source = await (await request.post(`/api/cycles/${cycle.id}/sources`, { data: { source_type: '测试', name: '交互测试来源', short_label: 'U', default_grade: 1110 } })).json();
  await request.put(`${prefix}/preferences`, { data: { target_grade: 1110, comparison_mode: 'combined' } });
  const equipment = { cycle_origin_id: cycle.id, source_id: source.id, equipment_type: 'hat', actual_grade: 1110, has_constitution_socket: true, green_stats_ok: true };
  const bad = { ...equipment, actual_grade: 965, has_constitution_socket: false, green_stats_ok: false };
  await request.put(`${prefix}/characters/${a.id}/equipment/hat`, { data: { expected_version: 0, equipment, choices: { enchant: { state: 'configured', name: '原有附魔' } } } });
  for (const [item, quantity] of [[equipment, 1], [bad, 2]] as const) await request.post(`${prefix}/warehouse`, { data: { request_id: crypto.randomUUID(), equipment: item, quantity } });
  const state = async () => (await request.get(`${prefix}/daily`)).json();
  const matrix = async () => (await request.get(`${prefix}/matrix`)).json();
  const dialog = page.getByRole('dialog');
  // Exercise a real non-secure origin, as used by NAS LAN deployments.
  await page.route('http://jx3-http.test/**', async route => {
    const url = new URL(route.request().url());
    await route.fulfill({ response: await route.fetch({ url: `http://127.0.0.1:8765${url.pathname}${url.search}` }) });
  });
  await page.goto('http://jx3-http.test/');
  expect(await page.evaluate(() => isSecureContext)).toBe(false);
  expect(await page.evaluate(() => typeof crypto.randomUUID)).toBe('undefined');
  await page.getByLabel('游戏账号', { exact: true }).selectOption(account.id);
  await page.getByRole('button', { name: '交互乙 帽子', exact: true }).click();
  await expect(dialog.getByRole('radiogroup', { name: '选择仓库装备' })).toBeVisible();
  await dialog.locator('.warehouse-option').filter({ hasText: '1110 品' }).click();
  await expect(dialog.getByLabel('穿戴角色')).toHaveCount(0);
  await expect(dialog.getByLabel('穿戴部位')).toHaveCount(0);
  await expect(dialog.getByRole('heading', { name: '交互乙 · 帽子', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await matrix()).cells[b.id].hat.equipment.actual_grade).toBe(1110);

  await page.getByRole('button', { name: '交互甲 帽子', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '保存记录', exact: true })).toBeDisabled();
  await dialog.getByText('更多信息', { exact: true }).click();
  await expect(dialog.getByLabel('附魔名称', { exact: true })).toHaveValue('原有附魔');
  await dialog.getByRole('group', { name: '绿字是否达标' }).getByRole('radio', { name: '未达标', exact: true }).check();
  await expect(dialog.getByLabel('附魔名称', { exact: true })).toHaveValue('原有附魔');
  await dialog.getByRole('button', { name: '保存记录', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await matrix()).cells[a.id].hat.choices.enchant.name).toBe('原有附魔');
  await page.getByRole('button', { name: '交互甲 帽子', exact: true }).click();
  await dialog.getByRole('button', { name: '手动换装', exact: true }).click();
  await dialog.getByLabel('来源预设').selectOption(source.id);
  await dialog.getByRole('group', { name: '是否有体质孔' }).getByRole('radio', { name: '有', exact: true }).check();
  await dialog.getByRole('group', { name: '绿字是否达标' }).getByRole('radio', { name: '达标', exact: true }).check();
  await dialog.getByText('更多信息', { exact: true }).click();
  await expect(dialog.getByLabel('附魔', { exact: true })).toHaveValue('unknown');
  await dialog.getByRole('button', { name: '确认更换装备', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await matrix()).cells[a.id].hat.choices.enchant.state).toBe('unknown');

  await page.getByRole('button', { name: '交互甲 帽子', exact: true }).click();
  await dialog.getByRole('button', { name: /从仓库穿戴/ }).click();
  await expect(dialog).toContainText('新装备比当前装备差');
  await dialog.getByText('附魔', { exact: true }).click();
  await dialog.getByLabel('附魔', { exact: true }).selectOption('configured');
  await dialog.getByLabel('附魔名称', { exact: true }).fill('本件附魔');
  await expect(dialog.getByTestId('equip-choice-summary')).toContainText('本件附魔');
  await page.setViewportSize({ width: 1100, height: 900 });
  await dialog.screenshot({ path: '../.tools/screenshots/ux-cell-warehouse.png' });
  await dialog.getByRole('button', { name: '确认换成较低配置', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(1);
  expect((await state()).warehouse[0].choices.enchant.state).toBe('unknown');
  await page.getByRole('button', { name: '给角色穿戴', exact: true }).click();
  await expect(dialog.getByLabel('穿戴角色')).toHaveValue('');
  await expect(dialog.getByRole('button', { name: '确认穿戴', exact: true })).toBeDisabled();
  await expect(dialog.getByLabel('穿戴部位')).toHaveCount(0);
  await dialog.getByRole('button', { name: '取消', exact: true }).click();

  await request.post(`${prefix}/drops`, { data: { request_id: crypto.randomUUID(), equipment: bad, quantity: 1 } });
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await page.getByRole('tab', { name: '本次团本掉落', exact: true }).click();
  await page.getByRole('button', { name: '转入仓库', exact: true }).click();
  await expect(dialog.getByLabel('实际获得的数量')).toHaveCount(0);
  await dialog.screenshot({ path: '../.tools/screenshots/ux-single-drop.png' });
  await dialog.getByRole('button', { name: '确认转入', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await state()).warehouse[0].quantity).toBe(2);
  await page.getByRole('tab', { name: '共享仓库', exact: true }).click();
  const historyCount = (await (await request.get(`${prefix}/history`)).json()).length;
  await page.getByRole('button', { name: '修改U-数量', exact: true }).click();
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByLabel('实际数量')).toHaveCount(0);
  expect((await (await request.get(`${prefix}/history`)).json()).length).toBe(historyCount);
  await page.getByRole('button', { name: '修改U-数量', exact: true }).click();
  await page.getByLabel('实际数量').fill('3');
  await page.route(`**/api/accounts/${account.id}/daily`, route => route.fulfill({ status: 503, json: { detail: '测试刷新中断' } }), { times: 1 });
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('操作已提交，但页面刷新失败');
  expect((await state()).warehouse[0].quantity).toBe(3);
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByLabel('实际数量')).toHaveCount(0);
  expect((await state()).warehouse[0].quantity).toBe(3);
  await page.getByRole('button', { name: '添加库存', exact: true }).click();
  await dialog.getByLabel('来源预设').selectOption(source.id);
  await dialog.getByLabel('库存装备部位').selectOption('weapon');
  await expect(dialog.getByLabel('来源预设')).toHaveValue(source.id);
  await expect(dialog.getByLabel('真实品级', { exact: true })).toHaveValue('1110');
  await expect(dialog.getByRole('group', { name: '是否有体质孔' }).locator('input:checked')).toHaveCount(0);
  await expect(dialog.getByLabel('录入数量')).toBeVisible();
  await dialog.screenshot({ path: '../.tools/screenshots/ux-add.png' });
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('tab', { name: '缺口明细', exact: true }).click();
  await expect(page.getByLabel('只看仓库可改善')).toBeChecked();
  await page.getByLabel('只看仓库可改善').uncheck();
  await expect(page.getByRole('tabpanel').locator('tbody tr')).toHaveCount(23);
  await page.getByRole('tab', { name: '共享仓库', exact: true }).click();
  await page.getByRole('button', { name: '修改U-数量', exact: true }).click();
  await page.getByLabel('实际数量').fill('0');
  page.once('dialog', prompt => prompt.accept());
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByText('共享仓库还没有库存。')).toBeVisible();
  await request.post(`${prefix}/warehouse`, { data: { request_id: crypto.randomUUID(), equipment: { ...equipment, equipment_type: 'ring' }, quantity: 2 } });
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await page.getByRole('button', { name: '给角色穿戴', exact: true }).click();
  await expect(dialog.getByLabel('穿戴部位').locator('option')).toHaveCount(2);
  await dialog.getByLabel('穿戴角色').selectOption(b.id);
  await dialog.getByLabel('穿戴部位').selectOption('ring2');
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await matrix()).cells[b.id].ring2.equipment.equipment_type).toBe('ring');
  expect((await matrix()).cells[b.id].ring1.equipment).toBeNull();
  await page.getByRole('button', { name: '交互甲 戒指1', exact: true }).click();
  await expect(dialog.getByLabel('穿戴部位')).toHaveCount(0);
  await expect(dialog.getByLabel('穿戴角色')).toHaveCount(0);
  await dialog.getByRole('button', { name: '确认穿戴', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  expect((await matrix()).cells[a.id].ring1.equipment.equipment_type).toBe('ring');
  expect((await state()).warehouse).toHaveLength(0);
  expect(failures).toEqual([]);
});
