import { expect, test } from '@playwright/test';
import { readFile } from 'node:fs/promises';

test('数据维护：下载、无效文件、预览取消、冲突保护、JSON 导入及备份恢复', async ({page,request})=>{
  const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message));
  const cycle=await (await request.post('/api/cycles',{data:{name:'数据验收周期'}})).json();
  const account=await (await request.post('/api/accounts',{data:{name:'数据验收账号'}})).json();
  const character=await (await request.post(`/api/accounts/${account.id}/characters`,{data:{name:'数据验收角色'}})).json();
  await request.put(`/api/accounts/${account.id}/characters/${character.id}/equipment/hat`,{data:{expected_version:0,equipment:{cycle_origin_id:cycle.id,equipment_type:'hat',actual_grade:1110,has_constitution_socket:true,green_stats_ok:true,base_constitution_override:0}}});
  await page.goto('/');
  await page.getByLabel('游戏账号',{exact:true}).selectOption(account.id);
  await page.getByRole('button',{name:'数据与备份',exact:true}).click();
  const dialog=page.getByRole('dialog');
  const actions=dialog.locator('.button-row').first().locator(':scope > :is(button,.file-button)');
  await expect(actions).toHaveCount(3);
  for (const width of [1280, 390]) {
    await page.setViewportSize({width,height:844});
    const styles=await actions.evaluateAll(elements=>elements.map(element=>{
      const {fontSize,fontWeight,lineHeight,borderRadius}=getComputedStyle(element);
      return {fontSize,fontWeight,lineHeight,borderRadius,height:element.getBoundingClientRect().height};
    }));
    expect(styles[0]).toEqual(styles[1]);
    expect(styles[0]).toEqual(styles[2]);
    const tops=await actions.evaluateAll(elements=>elements.map(element=>element.getBoundingClientRect().top));
    expect(new Set(tops).size).toBe(1);
    expect(await dialog.evaluate(element=>element.scrollWidth<=element.clientWidth)).toBe(true);
    await dialog.screenshot({path:`../.tools/screenshots/menu-backup-${width}.png`});
  }
  await page.setViewportSize({width:1280,height:844});
  let download=page.waitForEvent('download');
  await dialog.getByRole('button',{name:'导出 JSON',exact:true}).click();
  const jsonFile=await download;
  const raw=await readFile((await jsonFile.path())!);
  const payload=JSON.parse(raw.toString('utf8'));
  expect(payload.format).toBe('jx3-equipment-workspace');
  expect(payload.tables.character_slot_settings.find((r:any)=>r.character_id===character.id).refine_level).toBeNull();
  expect(payload.tables.equipment_templates.some((r:any)=>r.base_constitution_override===0)).toBe(true);
  download=page.waitForEvent('download');
  await dialog.getByRole('button',{name:'备份并下载数据库',exact:true}).click();
  const dbFile=await download;
  const dbRaw=await readFile((await dbFile.path())!);
  expect(dbRaw.subarray(0,16).toString()).toBe('SQLite format 3\0');
  await dialog.getByLabel('导入或恢复文件').setInputFiles({name:'错误.json',mimeType:'application/json',buffer:Buffer.from('{}')});
  await expect(dialog.getByRole('alert')).toContainText('不是完整的工作空间');
  const file={name:'工作空间.json',mimeType:'application/json',buffer:raw};
  const extra=await (await request.post('/api/accounts',{data:{name:'之后新增的测试账号'}})).json();
  await dialog.getByLabel('导入或恢复文件').setInputFiles(file);
  await expect(dialog.getByRole('region',{name:'工作空间替换预览'})).toBeVisible();
  await expect(dialog.getByRole('button',{name:'确认替换并备份',exact:true})).toBeDisabled();
  await dialog.getByText('查看名称与记录变化',{exact:true}).click();
  await expect(dialog.getByRole('region',{name:'工作空间替换预览'})).toContainText('之后新增的测试账号');
  await dialog.getByRole('button',{name:'返回',exact:true}).click();
  expect((await (await request.get('/api/workspace')).json()).accounts.some((a:any)=>a.id===extra.id)).toBe(true);
  await dialog.getByLabel('导入或恢复文件').setInputFiles(file);
  await expect(dialog.getByRole('heading',{name:'JSON 导入预览',exact:true})).toBeVisible();
  await request.put(`/api/accounts/${extra.id}/preferences`,{data:{target_grade:1200,comparison_mode:'strict'}});
  await dialog.getByLabel('确认整体替换工作空间').check();
  await dialog.getByRole('button',{name:'确认替换并备份',exact:true}).click();
  await expect(dialog.getByRole('alert')).toContainText('工作空间已变化');
  await dialog.getByRole('button',{name:'返回',exact:true}).click();
  await dialog.getByLabel('导入或恢复文件').setInputFiles(file);
  await dialog.getByLabel('确认整体替换工作空间').check();
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await dialog.evaluate(element=>{element.scrollTop=0;});
  await dialog.screenshot({path:'../.tools/screenshots/phase5-import-mobile.png'});
  await dialog.getByRole('button',{name:'确认替换并备份',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  expect((await (await request.get('/api/workspace')).json()).accounts.some((a:any)=>a.id===extra.id)).toBe(false);
  await request.put(`/api/accounts/${account.id}`,{data:{name:'错误修改的账号名'}});
  await page.getByRole('button',{name:'数据与备份',exact:true}).click();
  await dialog.getByLabel('导入或恢复文件').setInputFiles({name:dbFile.suggestedFilename(),mimeType:'application/vnd.sqlite3',buffer:dbRaw});
  await expect(dialog.getByRole('heading',{name:'数据库恢复预览',exact:true})).toBeVisible();
  await dialog.getByText('查看名称与记录变化',{exact:true}).click();
  await expect(dialog.getByRole('region',{name:'工作空间替换预览'})).toContainText('错误修改的账号名');
  await dialog.getByLabel('确认整体替换工作空间').check();
  await dialog.getByRole('button',{name:'确认替换并备份',exact:true}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.getByRole('heading',{name:'数据验收账号装备矩阵'})).toBeVisible();
  await page.getByRole('button',{name:'数据与备份',exact:true}).click();
  const stored=dialog.getByRole('group',{name:dbFile.suggestedFilename(),exact:true});
  await expect(stored).toBeVisible();
  const backupsBefore = await (await request.get('/api/data/backups')).json();
  await stored.getByRole('button',{name:'预览恢复',exact:true}).click();
  await expect(dialog.getByRole('heading',{name:'数据库恢复预览',exact:true})).toBeVisible();
  await dialog.getByRole('button',{name:'返回',exact:true}).click();
  page.once('dialog', prompt => prompt.dismiss());
  await stored.getByRole('button',{name:'删除备份',exact:true}).click();
  await expect(stored).toBeVisible();
  page.once('dialog', prompt => prompt.accept());
  await stored.getByRole('button',{name:'删除备份',exact:true}).click();
  await expect(stored).toHaveCount(0);
  expect((await request.get(`/api/data/backups/${dbFile.suggestedFilename()}`)).status()).toBe(404);
  expect(await (await request.get('/api/data/backups')).json()).toEqual(
    backupsBefore.filter((backup: {name: string}) => backup.name !== dbFile.suggestedFilename()),
  );
  expect(errors).toEqual([]);
});
