import { expect, test } from '@playwright/test';

test('多账号连续创建角色、切换草稿、移除与恢复保持归属及装备', async ({ page, request }) => {
  const suffix = Date.now();
  const first = await (await request.post('/api/accounts', { data: { name: `甲账号${suffix}`, sort_order: 0 } })).json();
  await page.goto('/');
  await page.getByLabel('游戏账号', { exact: true }).selectOption(first.id);
  await page.getByRole('button', { name: '账号与角色', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByRole('button', { name: '＋ 添加账号', exact: true }).click();
  await dialog.getByLabel('管理名称').fill(`乙账号${suffix}`);
  await dialog.getByRole('button', { name: '保存账号', exact: true }).click();
  await expect(dialog.getByText(`当前账号角色 · 乙账号${suffix}`, { exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: '＋ 添加角色', exact: true }).click();
  await dialog.getByLabel('管理名称').fill('乙角色');
  await dialog.getByRole('button', { name: '保存角色', exact: true }).click();
  const row = dialog.locator('.entity-row').filter({ hasText: '乙角色' });
  await expect(row).toBeVisible();
  expect(await (await request.get(`/api/accounts/${first.id}/characters`)).json()).toEqual([]);
  const second = (await (await request.get('/api/workspace')).json()).accounts.find((a: { name: string }) => a.name === `乙账号${suffix}`);
  const character = (await (await request.get(`/api/accounts/${second.id}/characters`)).json())[0];
  const cycle = await (await request.post('/api/cycles', { data: { name: `角色恢复测试${suffix}` } })).json();
  const worn = await request.put(`/api/accounts/${second.id}/characters/${character.id}/equipment/hat`, { data: { expected_version: 0, equipment: { cycle_origin_id: cycle.id, equipment_type: 'hat', source_type: '特殊', source_name: '测试来源', short_label: '测', actual_grade: 1234, has_constitution_socket: true, green_stats_ok: true } } });
  expect(worn.ok()).toBeTruthy();
  await row.getByRole('button', { name: '编辑', exact: true }).click();
  await dialog.getByLabel('管理名称').fill('未保存名称');
  page.once('dialog', prompt => prompt.dismiss());
  await dialog.getByLabel('管理账号', { exact: true }).selectOption(first.id);
  await expect(dialog.getByLabel('管理名称')).toHaveValue('未保存名称');
  page.once('dialog', prompt => prompt.accept());
  await dialog.getByLabel('管理账号', { exact: true }).selectOption(first.id);
  await expect(dialog.getByLabel('管理名称')).toHaveCount(0);
  await dialog.getByLabel('管理账号', { exact: true }).selectOption({ label: `乙账号${suffix}` });
  page.once('dialog', prompt => prompt.accept());
  await row.getByRole('button', { name: '移除角色', exact: true }).click();
  await expect(dialog.getByText('这个账号还没有角色', { exact: true })).toBeVisible();
  await dialog.getByText('已移除角色（1）', { exact: true }).click();
  await row.getByRole('button', { name: '恢复角色', exact: true }).click();
  await expect(row.getByRole('button', { name: '移除角色', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(page.locator('.matrix thead')).toContainText('乙角色');
  const raid = page.getByRole('group', { name: '乙角色 副本完成记录' });
  await expect(raid.getByRole('checkbox')).toHaveCount(3);
  await expect(raid.getByRole('checkbox', { checked: true })).toHaveCount(0);
  await raid.getByRole('checkbox', { name: '10人' }).check();
  await expect(raid.getByRole('checkbox', { name: '10人' })).toBeChecked();
  await raid.getByRole('checkbox', { name: '25yx' }).check();
  await expect(raid.getByRole('checkbox', { name: '25yx' })).toBeChecked();
  await expect(raid.getByRole('checkbox', { name: '25yx' })).toBeEnabled();
  await page.reload();
  await expect(raid.getByRole('checkbox', { name: '10人' })).toBeChecked();
  await expect(raid.getByRole('checkbox', { name: '25pt' })).not.toBeChecked();
  await expect(raid.getByRole('checkbox', { name: '25yx' })).toBeChecked();
  await raid.getByRole('checkbox', { name: '10人' }).uncheck();
  await expect(raid.getByRole('checkbox', { name: '10人' })).not.toBeChecked();
  await page.route('**/raid-checks/25pt', route => route.fulfill({ status: 503, json: { detail: '测试保存失败' } }), { times: 1 });
  await raid.getByRole('checkbox', { name: '25pt' }).click();
  await expect(page.getByRole('alert')).toHaveText('测试保存失败');
  await expect(raid.getByRole('checkbox', { name: '25pt' })).not.toBeChecked();
  await expect(page.getByRole('button', { name: '乙角色 帽子', exact: true })).toHaveAccessibleDescription(/1234 品/);
  await page.getByRole('button', { name: '乙角色 帽子', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '清除穿戴', exact: true })).toBeVisible();
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '账号与角色', exact: true }).click();
  await row.getByRole('button', { name: '编辑', exact: true }).click();
  await dialog.getByLabel('管理名称').fill('关闭保护');
  page.once('dialog', prompt => prompt.dismiss());
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await expect(dialog.getByLabel('管理名称')).toHaveValue('关闭保护');
  page.once('dialog', prompt => prompt.accept());
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '账号与角色', exact: true }).click();
  page.once('dialog', prompt => prompt.accept());
  await dialog.locator('.entity-row').filter({ hasText: `乙账号${suffix}` }).getByRole('button', { name: '归档', exact: true }).click();
  await expect(page.getByLabel('游戏账号', { exact: true })).not.toHaveValue(second.id);
  await dialog.getByText('已归档账号（1）', { exact: true }).click();
  await dialog.locator('.entity-row').filter({ hasText: `乙账号${suffix}` }).getByRole('button', { name: '恢复', exact: true }).click();
  await dialog.getByLabel('管理账号', { exact: true }).selectOption(second.id);
  await expect(row).toBeVisible();
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(dialog.getByRole('button', { name: '移除角色', exact: true })).toBeVisible();
  expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true);
  await page.screenshot({ path: '../.tools/screenshots/0.1.2-people-mobile.png', fullPage: true });
});
