test('0.1.11：来源切换带出品级、完整预览、直接删除、勾选入库和自动 CD 设置', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const cycle = await (await request.post('/api/cycles', { data: { name: '0111浏览器示意周期' } })).json();
  const account = await (await request.post('/api/accounts', { data: { name: '0111浏览器示意账号' } })).json();
  const base = `/api/accounts/${account.id}`;
  const character = await (await request.post(base + '/characters', { data: { name: '0111浏览器角色' } })).json();
  const source = await (await request.post(`/api/cycles/${cycle.id}/sources`, { data: { source_type: '测试', name: '0111来源甲', short_label: '甲', actual_grade: 1110 } })).json();
  const other = await (await request.post(`/api/cycles/${cycle.id}/sources`, { data: { source_type: '测试', name: '0111来源乙', short_label: '乙', actual_grade: 965 } })).json();
  const highId = await fixtureSource(request, cycle.id, 1200);
  const gear = { source_id: source.id, equipment_type: 'hat', has_constitution_socket: true, green_stats_ok: true, base_constitution_override: 42 };
  await request.put(base + `/characters/${character.id}/equipment/hat`, { data: { expected_version: 0, equipment: gear } });
  await page.goto('/');
  await page.getByLabel('游戏账号', { exact: true }).selectOption(account.id);
  const dialog = page.getByRole('dialog');
  await page.getByRole('button', { name: '0111浏览器角色 帽子', exact: true }).click();
  await dialog.getByLabel('来源预设').selectOption(other.id);
  await expect(dialog.getByLabel('真实品级', { exact: true })).toHaveText('965');
  page.once('dialog', prompt => prompt.accept());
  await dialog.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '0111浏览器角色 批量录入装备', exact: true }).click();
  await dialog.getByLabel('帽子批量操作', { exact: true }).selectOption('edit');
  await dialog.getByText('帽子更多属性', { exact: true }).click();
  await dialog.getByLabel('帽子批量体质覆盖', { exact: true }).fill('99');
  await dialog.getByLabel('帽子批量装备名称', { exact: true }).fill('预览名称示意');
  await dialog.getByRole('button', { name: '预览整批更改', exact: true }).click();
  await expect(dialog.getByLabel('角色批量预览')).toContainText('基础体质覆盖：42');
  await expect(dialog.getByLabel('角色批量预览')).toContainText('基础体质覆盖：99');
  await expect(dialog.getByLabel('角色批量预览')).toContainText('预览名称示意');
  await dialog.screenshot({ path: '../.tools/0111-batch-preview.png' });
  await dialog.getByRole('button', { name: '确认整批保存并备份', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  for (const [grade, quantity] of [[1110, 2], [1200, 3]]) {
    await request.post(base + '/drops', { data: { request_id: crypto.randomUUID(), equipment: { ...gear, source_id: grade === 1110 ? source.id : highId }, quantity } });
  }
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await page.getByRole('button', { name: '团本掉落', exact: true }).click();
  await page.getByRole('button', { name: '选择当前筛选结果', exact: true }).click();
  page.once('dialog', prompt => prompt.accept());
  await page.getByRole('button', { name: '所选一键入库 · 2 项', exact: true }).click();
  await expect(page.getByText('本次还没有记录掉落。', { exact: true })).toBeVisible();
  let daily = await (await request.get(base + '/daily')).json();
  expect(daily.warehouse.reduce((sum: number, item: { quantity: number }) => sum + item.quantity, 0)).toBe(5);
  await page.getByRole('button', { name: '编辑帽子共享仓库配置1', exact: true }).click();
  await expect(dialog.getByRole('button', { name: '删除库存', exact: true })).toBeVisible();
  page.once('dialog', prompt => prompt.accept());
  await dialog.getByRole('button', { name: '删除库存', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  daily = await (await request.get(base + '/daily')).json();
  expect(daily.warehouse).toHaveLength(1);
  await request.post(base + '/drops', { data: { request_id: crypto.randomUUID(), equipment: { ...gear, equipment_type: 'ring' }, quantity: 2 } });
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  page.once('dialog', prompt => prompt.accept());
  await page.getByRole('button', { name: '一键入库戒指1掉落配置1', exact: true }).click();
  await expect(page.getByRole('button', { name: '一键入库戒指1掉落配置1', exact: true })).toHaveCount(0);
  daily = await (await request.get(base + '/daily')).json();
  expect(daily.warehouse.find((item: {equipment: {equipment_type: string}}) => item.equipment.equipment_type === 'ring').quantity).toBe(2);
  await page.getByRole('button', { name: '账号与角色', exact: true }).click();
  const toggle = dialog.getByRole('checkbox', { name: '副本 CD 自动重置', exact: true });
  await expect(toggle).not.toBeChecked();
  page.once('dialog', prompt => prompt.accept());
  await toggle.check();
  await expect(toggle).toBeChecked();
  await expect(toggle).toBeEnabled();
  expect((await (await request.get('/api/raid-cd')).json()).enabled).toBe(true);
  page.once('dialog', prompt => prompt.accept());
  await toggle.uncheck();
  await expect(toggle).not.toBeChecked();
  await expect(toggle).toBeEnabled();
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await dialog.screenshot({ path: '../.tools/0111-people-mobile.png' });
  expect(errors).toEqual([]);
});

test('账号创建响应丢失后核对不重复，误建空角色及空账号可删除', async ({ page, request }) => {
  await page.goto('/');
  if (await page.getByRole('button', { name: '添加账号与角色', exact: true }).isVisible()) {
    await page.getByRole('button', { name: '添加账号与角色', exact: true }).click();
  } else {
    await page.getByRole('button', { name: '账号与角色', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: '＋ 添加账号', exact: true }).click();
  }
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('管理名称').fill('0111创建丢失示意账号');
  await page.route('**/api/accounts', async route => { expect((await route.fetch()).ok()).toBe(true); await route.abort('connectionreset'); }, { times: 1 });
  await dialog.getByRole('button', { name: '保存账号', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('操作结果待核对');
  page.once('dialog', prompt => prompt.accept());
  await dialog.getByRole('button', { name: '关闭', exact: true }).click();
  await page.getByRole('button', { name: '核对上一笔操作 · 账号创建', exact: true }).click();
  await expect(page.getByLabel('待核对操作')).toHaveCount(0);
  let accounts = (await (await request.get('/api/workspace')).json()).accounts;
  expect(accounts.filter((item: {name: string}) => item.name === '0111创建丢失示意账号')).toHaveLength(1);
  const account = accounts.find((item: {name: string}) => item.name === '0111创建丢失示意账号');
  await page.getByLabel('游戏账号', { exact: true }).selectOption(account.id);
  await page.getByRole('button', { name: '账号与角色', exact: true }).click();
  await dialog.getByRole('button', { name: '＋ 添加角色', exact: true }).click();
  await dialog.getByLabel('管理名称').fill('0111误建空角色');
  await dialog.getByRole('button', { name: '保存角色', exact: true }).click();
  const row = dialog.locator('.entity-row').filter({ hasText: '0111误建空角色' });
  await expect(row).toBeVisible();
  page.once('dialog', prompt => prompt.accept());
  await row.getByRole('button', { name: '删除空角色', exact: true }).click();
  await expect(row).toHaveCount(0);
  const accountRow = dialog.locator('.entity-row').filter({ hasText: '0111创建丢失示意账号' });
  page.once('dialog', prompt => prompt.accept());
  await accountRow.getByRole('button', { name: '删除空账号', exact: true }).click();
  await expect(accountRow).toHaveCount(0);
  accounts = (await (await request.get('/api/workspace')).json()).accounts;
  expect(accounts.some((item: {id: string}) => item.id === account.id)).toBe(false);
});

test('未知结果取消后仍可独立核对；单格冲突保留输入采用最新版本', async ({ page, request }) => {
  const cycle = await (await request.post('/api/cycles', { data: { name: '0111恢复示意周期' } })).json();
  const account = await (await request.post('/api/accounts', { data: { name: '0111恢复示意账号' } })).json();
  const base = `/api/accounts/${account.id}`;
  const character = await (await request.post(base + '/characters', { data: { name: '0111恢复角色' } })).json();
  const sourceId = await fixtureSource(request, cycle.id, 1110);
  const lowId = await fixtureSource(request, cycle.id, 965);
  const highId = await fixtureSource(request, cycle.id, 1200);
  const gear = { source_id: sourceId, equipment_type: 'hat', has_constitution_socket: true, green_stats_ok: true };
  const stock = await (await request.post(base + '/warehouse', { data: { request_id: crypto.randomUUID(), equipment: gear, quantity: 2 } })).json();
  await page.goto('/');
  await page.getByLabel('游戏账号', { exact: true }).selectOption(account.id);
  await page.getByRole('button', { name: '共享仓库', exact: true }).click();
  await page.getByRole('button', { name: `修改${stock.label}数量`, exact: true }).click();
  await page.getByLabel('实际数量').fill('3');
  await page.route(`**/warehouse/${stock.id}/quantity`, async route => { expect((await route.fetch()).ok()).toBe(true); await route.abort('connectionreset'); }, { times: 1 });
  await page.getByRole('button', { name: '保存数量', exact: true }).click();
  await expect(page.getByRole('alert')).toContainText('操作结果待核对');
  await page.getByRole('button', { name: '取消修改数量', exact: true }).click();
  await expect(page.getByLabel('实际数量')).toHaveCount(0);
  await page.getByRole('button', { name: '核对上一笔操作 · 数量修改', exact: true }).click();
  await expect(page.getByLabel('待核对操作')).toHaveCount(0);
  expect((await (await request.get(base + '/daily')).json()).warehouse[0].quantity).toBe(3);
  const url = base + `/characters/${character.id}/equipment/chest`;
  await request.put(url, { data: { expected_version: 0, equipment: { ...gear, equipment_type: 'chest' } } });
  await page.getByRole('button', { name: '刷新', exact: true }).click();
  await page.getByRole('button', { name: '0111恢复角色 上衣', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('来源预设', { exact: true }).selectOption(highId);
  await request.put(url, { data: { expected_version: 1, equipment: { ...gear, equipment_type: 'chest', source_id: lowId } } });
  await dialog.getByRole('button', { name: '保存记录', exact: true }).click();
  await expect(dialog.getByRole('alert')).toContainText('此格装备已在其他页面修改');
  await dialog.getByRole('button', { name: '读取最新记录核对', exact: true }).click();
  await dialog.getByRole('button', { name: '保留输入并采用最新版本', exact: true }).click();
  await expect(dialog.getByLabel('真实品级', { exact: true })).toHaveText('1200');
  await dialog.getByRole('button', { name: '保存记录', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const matrix = await (await request.get(base + '/matrix')).json();
  expect(matrix.cells[character.id].chest.equipment.actual_grade).toBe(1200);
});
